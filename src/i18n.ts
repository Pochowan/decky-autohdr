const STRINGS: Record<Lang, Dict> = { es, en, fr, de, it, pt, ca, zh, ja, ru };

/** Idioma de Steam (nombre interno de Steam o etiqueta BCP-47) -> código propio. */
export function mapSteamLanguage(raw: string | undefined | null): Lang {
  const s = (raw || "").toLowerCase();
  const table: Record<string, Lang> = {
    spanish: "es", latam: "es", english: "en", french: "fr", german: "de", italian: "it",
    portuguese: "pt", brazilian: "pt", catalan: "ca", schinese: "zh", tchinese: "zh",
    japanese: "ja", russian: "ru",
  };
  if (table[s]) return table[s];
  const prefix = s.split(/[-_]/)[0];
  if ((LANGUAGES as readonly { code: string }[]).some((l) => l.code === prefix)) return prefix as Lang;
  return "en";
}

export function translate(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  let s: string = (STRINGS[lang] ?? en)[key] ?? en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
